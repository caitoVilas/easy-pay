package com.caito.merchantservice.utils.enums;

/*
* Enum representing different types of businesses.
* RETAIL: Businesses involved in selling goods directly to consumers.
* FOOD_SERVICE: Businesses that provide food and beverage services.
* E_COMMERCE: Businesses that operate online stores.
* SERVICES: Businesses that offer various services rather than physical products.
* PROFESSIONAL: Businesses that provide professional services such as consulting, legal, or financial services.
* HEALTHCARE: Businesses involved in providing medical and health-related services.
* EDUCATION: Businesses that offer educational services and training.
* ENTERTAINMENT: Businesses that provide entertainment services such as theaters, gaming, and events.
* OTHER: Any other type of business not categorized above.
*
* @author caito
*
 */
public enum BusinessYtpe {
    RETAIL,
    FOOD_SERVICE,
    E_COMMERCE,
    SERVICES,
    PROFESSIONAL,
    HEALTHCARE,
    EDUCATION,
    ENTERTAINMENT,
    OTHER
}
